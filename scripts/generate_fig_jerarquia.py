"""
generate_fig_jerarquia.py

Reproduces Figure `fig:jerarquia` (fig_jerarquia.pdf) of the JORS
manuscript: "Hierarchical stratification of the decision variables in
the MILP model."

Data provenance
----------------
Unlike fig2-fig5, this figure is conceptual rather than data-driven: it
illustrates the three-level decision architecture of the model (Section
4.4/4.1) and does not encode any experimental result. It is nonetheless
generated by this script, rather than left as inline TikZ, for
consistency with the reproducibility standard adopted for every other
figure in the article (Section 5) — every visual artifact in the paper
should be regenerable from a single, version-controlled source.

The three levels and their governing variables are:
    Level 1 - Strategic Academic Assignment  -> y_{p,m,g}
    Level 2 - Temporal Scheduling             -> y_{p,m,g,s,h,d}
    Level 3 - Infrastructure Allocation       -> x_{a,m,g,s,h,d}
matching Section 4.4 (Decision variables) of main.tex exactly.

Usage
-----
    python3 generate_fig_jerarquia.py [output_path]

Default output_path is ../fig_jerarquia.pdf (relative to this script).
Using this figure in main.tex requires replacing the inline
tikzpicture block for fig:jerarquia with
\\includegraphics[width=0.8\\textwidth]{fig_jerarquia} (done separately
once this script's output is approved).
"""

import sys
from pathlib import Path

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
import matplotlib.patches as mpatches
from matplotlib.patches import FancyArrowPatch

LEVELS = [
    ("Level 1: Strategic Academic Assignment",
     "Determination of ownership (Lecturer $\\rightarrow$ Course $\\rightarrow$ Cohort)",
     r"Main variable: $y_{p,m,g}$"),
    ("Level 2: Temporal Scheduling",
     "Workload distribution across time slots (Session $\\rightarrow$ Day $\\rightarrow$ Block)",
     r"Main variable: $y_{p,m,g,s,h,d}$"),
    ("Level 3: Infrastructure Allocation",
     "Topological and spatial anchoring (Activity $\\rightarrow$ Classroom / Laboratory)",
     r"Main variable: $x_{a,m,g,s,h,d}$"),
]

BOX_WIDTH = 8.0
BOX_HEIGHT = 1.5
GAP = 1.0


def build_figure(output_path: Path) -> None:
    plt.rcParams.update({
        "font.family": "DejaVu Sans",
        "font.size": 10.5,
    })

    n = len(LEVELS)
    fig_height = n * BOX_HEIGHT + (n - 1) * GAP + 0.6
    fig, ax = plt.subplots(figsize=(9, fig_height * 0.9), dpi=300)

    centers_y = []
    y = 0.0
    # place from top (Level 1) to bottom (Level 3); iterate reversed so
    # Level 1 ends up at the top of the drawing
    for i, _ in enumerate(LEVELS):
        top_y = (n - 1 - i) * (BOX_HEIGHT + GAP)
        centers_y.append(top_y)

    for (title, desc, var), y0 in zip(LEVELS, centers_y):
        box = mpatches.FancyBboxPatch(
            (-BOX_WIDTH / 2, y0), BOX_WIDTH, BOX_HEIGHT,
            boxstyle="round,pad=0.02,rounding_size=0.06",
            linewidth=1.4, edgecolor="black", facecolor="white", zorder=3,
        )
        ax.add_patch(box)
        cy = y0 + BOX_HEIGHT / 2
        ax.text(0, cy + 0.38, title, ha="center", va="center",
                fontsize=11, fontweight="bold", zorder=4)
        ax.text(0, cy + 0.02, desc, ha="center", va="center",
                fontsize=9.5, zorder=4, wrap=True)
        ax.text(0, cy - 0.40, var, ha="center", va="center",
                fontsize=9.5, style="italic", zorder=4)

    # downward arrows connecting consecutive levels
    for i in range(n - 1):
        y_from = centers_y[i]
        y_to = centers_y[i + 1] + BOX_HEIGHT
        arrow = FancyArrowPatch(
            (0, y_from), (0, y_to),
            arrowstyle="-|>", mutation_scale=20,
            linewidth=1.6, color="black", zorder=2,
        )
        ax.add_patch(arrow)

    ax.set_xlim(-BOX_WIDTH / 2 - 0.5, BOX_WIDTH / 2 + 0.5)
    ax.set_ylim(-0.3, centers_y[0] + BOX_HEIGHT + 0.3)
    ax.axis("off")

    fig.tight_layout()
    output_path.parent.mkdir(parents=True, exist_ok=True)
    fig.savefig(output_path, format="pdf")
    plt.close(fig)


if __name__ == "__main__":
    default_out = Path(__file__).resolve().parent.parent / "fig_jerarquia.pdf"
    out = Path(sys.argv[1]) if len(sys.argv) > 1 else default_out
    build_figure(out)
    print(f"Figure written to: {out}")
